def seed_if_empty(db):
    if Company.query.first():
        return
    for cid, name, industry, city in COMPANIES:
        db.session.add(Company(id=cid, name=name, industry=industry, city=city))
    for m in MANAGERS:
        db.session.add(Manager(**m))
    db.session.commit()
    print(f'Seeded {len(COMPANIES)} companies, {len(MANAGERS)} managers.')
